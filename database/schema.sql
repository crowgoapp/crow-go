-- Retrieve admin WhatsApp number for support/renewal contact
CREATE OR REPLACE FUNCTION public.get_admin_whatsapp()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p.whatsapp_phone
  FROM public.profiles p
  JOIN public.admins a ON a.user_id = p.id
  WHERE p.whatsapp_phone IS NOT NULL
    AND p.whatsapp_phone <> ''
  ORDER BY a.created_at ASC
  LIMIT 1;
$$;

GRANT EXECUTE ON FUNCTION public.get_admin_whatsapp() TO anon, authenticated;

-- Apply referral code at signup and reward +7 days for every 5 completed referrals
CREATE OR REPLACE FUNCTION public.apply_referral(p_code text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_referrer_id uuid;
  v_ref_count integer;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not authenticated';
  END IF;

  SELECT id INTO v_referrer_id
  FROM public.profiles
  WHERE referral_code = upper(trim(p_code))
    AND id <> auth.uid()
  LIMIT 1;

  IF v_referrer_id IS NULL THEN
    RAISE EXCEPTION 'كود الإحالة غير صحيح';
  END IF;

  INSERT INTO public.referrals (referrer_id, referred_id)
  VALUES (v_referrer_id, auth.uid());

  SELECT count(*) INTO v_ref_count
  FROM public.referrals
  WHERE referrer_id = v_referrer_id;

  IF v_ref_count % 5 = 0 THEN
    UPDATE public.profiles
    SET subscription_end = greatest(coalesce(subscription_end, now()), now()) + interval '7 days'
    WHERE id = v_referrer_id;
  END IF;
END;
$$;

GRANT EXECUTE ON FUNCTION public.apply_referral(text) TO authenticated;

-- Admin: Confirm pending payment (bigint id) and extend subscription
CREATE OR REPLACE FUNCTION public.confirm_payment(p_id bigint, p_days integer DEFAULT 30)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_waseet_id uuid;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'not allowed';
  END IF;

  UPDATE public.payments
  SET status = 'confirmed'
  WHERE id = p_id
    AND status = 'pending'
  RETURNING waseet_id INTO v_waseet_id;

  IF v_waseet_id IS NULL THEN
    RAISE EXCEPTION 'الطلب غير موجود أو تمت مراجعته بالفعل';
  END IF;

  UPDATE public.profiles
  SET subscription_end = greatest(coalesce(subscription_end, now()), now()) + make_interval(days => p_days)
  WHERE id = v_waseet_id;
END;
$$;

GRANT EXECUTE ON FUNCTION public.confirm_payment(bigint, integer) TO authenticated;

-- Admin: Reject pending payment (bigint id)
CREATE OR REPLACE FUNCTION public.reject_payment(p_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'not allowed';
  END IF;

  UPDATE public.payments
  SET status = 'rejected'
  WHERE id = p_id
    AND status = 'pending';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'الطلب غير موجود أو تمت مراجعته بالفعل';
  END IF;
END;
$$;

GRANT EXECUTE ON FUNCTION public.reject_payment(bigint) TO authenticated;

