-- Verify if the currently authenticated user is registered in public.admins
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.admins
    WHERE user_id = auth.uid()
  );
$$;

-- Verify if the currently authenticated user has a valid active subscription
CREATE OR REPLACE FUNCTION public.has_active_sub()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE id = auth.uid()
      AND subscription_end IS NOT NULL
      AND subscription_end > now()
  );
$$;

-- ----------------------------------------------------------------------------
-- 4. SIGNUP TRIGGER (Auto-provision profile, referral code & 7-day trial)
-- ----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_ref_code text;
BEGIN
  v_ref_code := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));

  INSERT INTO public.profiles (
    id,
    name,
    phone,
    governorate,
    profession,
    referral_code,
    subscription_end
  )
  VALUES (
    NEW.id,
    coalesce(NEW.raw_user_meta_data->>'name', ''),
    coalesce(NEW.raw_user_meta_data->>'phone', split_part(NEW.email, '@', 1)),
    coalesce(NEW.raw_user_meta_data->>'governorate', ''),
    coalesce(NEW.raw_user_meta_data->>'profession', ''),
    v_ref_code,
    now() + interval '7 days'
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

